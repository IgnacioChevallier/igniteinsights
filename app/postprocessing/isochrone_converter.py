"""
Converts ELMFIRE output shapefiles to GeoJSON for the API.

`hourly_isochrones.shp` is not a native ELMFIRE output — it's generated by the
elmfire-runner microservice running `gdal_contour -a arrival_s -i <DTDUMP>
time_of_arrival_*.tif hourly_isochrones.shp` after ELMFIRE exits (see
.claude/skills/elmfire/references/interface-gotchas.md). The `-a arrival_s` flag
stores each contour's level — the arrival time in seconds — as a feature attribute,
which is what `arrival_hours` is derived from here.

Runs produced before that flag was added carry only a sequential `ID`; their features
get `arrival_s = None` and render as "unknown" rather than being assigned a guessed
time. Re-run the simulation to get timed isochrones.
"""
import json
from pathlib import Path

import geopandas as gpd

_EMPTY: dict = {"type": "FeatureCollection", "features": []}


def shapefile_to_geojson(shp_path: Path) -> dict:
    """Return a GeoJSON FeatureCollection from an ELMFIRE shapefile, reprojected to
    EPSG:4326. Returns an empty FeatureCollection if the shapefile is missing or has
    zero features — both are normal states for a completed run."""
    if not shp_path.exists():
        return dict(_EMPTY)
    gdf = gpd.read_file(shp_path)
    if gdf.empty:
        return dict(_EMPTY)
    if gdf.crs is None:
        raise ValueError(f"{shp_path} has no CRS (.prj missing or unreadable)")
    return json.loads(gdf.to_crs(epsg=4326).to_json())


def isochrones_to_geojson(shp_path: Path) -> dict:
    """`shapefile_to_geojson` plus `arrival_s`/`arrival_hours` on every feature."""
    geojson = shapefile_to_geojson(shp_path)
    _normalize_arrival(geojson)
    return geojson


def _normalize_arrival(geojson: dict) -> None:
    """Derive `arrival_hours` from the `arrival_s` attribute gdal_contour wrote.

    Mutates `geojson` in place. A feature with no usable `arrival_s` (a pre-`-a`
    shapefile, or a null) gets both fields set to None so the map can style it as
    unknown instead of colouring it with a fabricated time.
    """
    for feature in geojson["features"]:
        props = feature["properties"]
        raw = props.get("arrival_s")
        try:
            arrival_s = float(raw) if raw is not None else None
        except (TypeError, ValueError):
            arrival_s = None
        props["arrival_s"] = arrival_s
        props["arrival_hours"] = None if arrival_s is None else round(arrival_s / 3600, 2)
