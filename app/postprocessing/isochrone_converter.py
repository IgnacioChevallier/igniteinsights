"""
Converts ELMFIRE output shapefiles to GeoJSON for the API.

`hourly_isochrones.shp` is not a native ELMFIRE output — it's generated by the
elmfire-runner microservice running `gdal_contour -i <DTDUMP> time_of_arrival_*.tif
hourly_isochrones.shp` after ELMFIRE exits (see
.claude/skills/elmfire/references/interface-gotchas.md). Because that invocation
doesn't pass `-a`/`-amin`, the resulting shapefile's only attribute is a sequential
`ID` — the arrival-time value each contour line represents isn't stored on the
feature. `enrich_with_arrival_time` recovers it by sampling the sibling
time_of_arrival raster.
"""
import json
from pathlib import Path

import geopandas as gpd
import rasterio
from pyproj import Transformer


def shapefile_to_geojson(shp_path: Path) -> dict:
    """Return a GeoJSON FeatureCollection from an ELMFIRE isochrones shapefile,
    reprojected to EPSG:4326. Returns an empty FeatureCollection if the shapefile
    is missing or has zero features — both are normal states for a completed run."""
    if not shp_path.exists():
        return {"type": "FeatureCollection", "features": []}
    gdf = gpd.read_file(shp_path)
    if gdf.empty:
        return {"type": "FeatureCollection", "features": []}
    if gdf.crs is None:
        raise ValueError(f"{shp_path} has no CRS (.prj missing or unreadable)")
    gdf = gdf.to_crs(epsg=4326)
    return json.loads(gdf.to_json())


def enrich_with_arrival_time(geojson: dict, time_of_arrival_tif: Path) -> dict:
    """Attach `arrival_s` / `arrival_hours` to each isochrone feature by sampling
    the time_of_arrival raster at the feature's midpoint coordinate. Mutates and
    returns `geojson`. No-op if there are no features or the raster is missing."""
    if not geojson["features"] or not time_of_arrival_tif.exists():
        return geojson

    with rasterio.open(time_of_arrival_tif) as ds:
        band = ds.read(1)
        nodata = ds.nodata
        transformer = Transformer.from_crs("EPSG:4326", ds.crs, always_xy=True)

        for feature in geojson["features"]:
            coords = feature["geometry"]["coordinates"]
            mid = coords[len(coords) // 2]
            x, y = transformer.transform(mid[0], mid[1])
            row, col = ds.index(x, y)

            arrival_s = None
            if 0 <= row < band.shape[0] and 0 <= col < band.shape[1]:
                val = float(band[row, col])
                if nodata is None or val != nodata:
                    arrival_s = val

            feature["properties"]["arrival_s"] = arrival_s
            feature["properties"]["arrival_hours"] = (
                round(arrival_s / 3600, 2) if arrival_s is not None else None
            )

    return geojson
